import { z } from "zod";

import { underVitest } from "@/lib/db/test-guard";
import { LOG_LEVELS, type LogLevel } from "@/lib/logging/levels";
import { resolveHostDatabaseUrl } from "@/lib/ops/doctor/database-url";

/**
 * Environment variables are an external boundary (C6): parse them with zod.
 * Parsing is lazy so `next build` never needs a database URL.
 * Every variable is documented in `.env.example`; tunables get a default here
 * until the config system lands.
 */

const databaseEnvSchema = z.object({
  DATABASE_URL: z
    .string({ error: "DATABASE_URL is not set" })
    .min(1, "DATABASE_URL is not set")
    .refine((value) => /^(postgresql|postgres):\/\//.test(value), "DATABASE_URL must be a postgres:// URL"),
  DB_POOL_MAX: z.coerce.number().int().min(1).max(100).default(10),
  /** Seconds to wait for a new connection before failing (raise it on a loaded machine, e.g. the integration tests). */
  DB_CONNECT_TIMEOUT_SECONDS: z.coerce.number().int().min(1).max(120).default(5),
  /** Defaults to the folder generated by the migration tool; resolved in `lib/db/migrate.ts`. */
  MIGRATIONS_DIR: z.string().min(1).optional(),
});

const runnerEnvSchema = z.object({
  RUNNER_HEARTBEAT_SECONDS: z.coerce.number().int().min(1).max(3600).default(30),
  RUNNER_HEARTBEAT_RETENTION_HOURS: z.coerce.number().int().min(1).max(24 * 365).default(24),
  /** The container healthcheck turns unhealthy when the newest heartbeat is older than this. */
  RUNNER_HEALTH_MAX_AGE_SECONDS: z.coerce.number().int().min(1).max(86_400).default(120),
  /** Where the scheduled pg_dump writes (relative paths resolve against the working directory). */
  RUNNER_BACKUP_DIR: z.string().min(1).default("data/backups"),
  /** The pg_dump executable; its major version must be >= the server's (the runner image ships 17). */
  PG_DUMP_PATH: z.string().min(1).default("pg_dump"),
  /** The pg_restore executable that validates each finished backup (`--list`); same version as pg_dump. */
  PG_RESTORE_PATH: z.string().min(1).default("pg_restore"),
});

/** Telegram credentials. Never echo the values (C4): messages name the variable only. */
const telegramEnvSchema = z.object({
  TELEGRAM_BOT_TOKEN: z.string().regex(/^\d+:[\w-]+$/, "is not a bot token (expected <digits>:<secret>)"),
  /** A private chat id is a positive integer; groups / channels are negative. */
  TELEGRAM_CHAT_ID: z.string().regex(/^-?\d+$/, "must be a numeric chat id"),
  /** Optional: comma-separated Telegram user ids allowed to press buttons (in a group chat anyone in the group could otherwise). */
  TELEGRAM_ALLOWED_USER_IDS: z.string().regex(/^\s*\d+(\s*,\s*\d+)*\s*,?\s*$/, "must be comma-separated numeric user ids").optional(),
});

export type DatabaseEnv = z.infer<typeof databaseEnvSchema>;
export type RunnerEnv = z.infer<typeof runnerEnvSchema>;
export type TelegramEnv = z.infer<typeof telegramEnvSchema>;

type EnvSource = Record<string, string | undefined>;

/** Treat empty strings (e.g. `FOO=` copied from .env.example) as unset. */
function withoutEmpty(source: EnvSource): Record<string, string | undefined> {
  return Object.fromEntries(Object.entries(source).filter(([, value]) => value !== ""));
}

/**
 * Error messages only name the offending variable, never its value, so a
 * malformed DATABASE_URL (which may embed a password) cannot leak (C4).
 */
function parseEnv<T extends z.ZodType>(schema: T, source: EnvSource): z.infer<T> {
  const result = schema.safeParse(withoutEmpty(source));
  if (!result.success) {
    const problems = result.error.issues.map((issue) => `${issue.path.join(".") || "env"}: ${issue.message}`);
    throw new Error(`Invalid environment: ${problems.join("; ")}`);
  }
  return result.data;
}

/**
 * An explicit DATABASE_URL wins. Without one the host-side address of the compose `db` service is used (built from the
 * `POSTGRES_*` / `DB_HOST_PORT` values, defaults included), so host commands work with an empty or missing `.env`.
 * Containers always get DATABASE_URL from compose. Under Vitest there is no default (a test without DATABASE_URL has no
 * database; it must never fall through to the compose database).
 */
export function loadDatabaseEnv(source: EnvSource = process.env): DatabaseEnv {
  if (underVitest(source)) return parseEnv(databaseEnvSchema, source);
  return parseEnv(databaseEnvSchema, { ...source, DATABASE_URL: resolveHostDatabaseUrl(source) });
}

export function loadRunnerEnv(source: EnvSource = process.env): RunnerEnv {
  return parseEnv(runnerEnvSchema, source);
}

/**
 * `null` when neither variable is set (Telegram is simply not configured yet). Setting only one of
 * them, or a malformed value, throws: that is a mistake worth surfacing.
 */
/** The user ids of `TELEGRAM_ALLOWED_USER_IDS` (already validated by `loadTelegramEnv`); null when unset: then anyone in the chat is served. */
export function parseAllowedUserIds(value: string | undefined): readonly number[] | null {
  if (value === undefined || value.trim() === "") return null;
  return value.split(",").map((part) => part.trim()).filter((part) => part !== "").map(Number);
}

export function loadTelegramEnv(source: EnvSource = process.env): TelegramEnv | null {
  const present = withoutEmpty(source);
  if (present.TELEGRAM_BOT_TOKEN === undefined && present.TELEGRAM_CHAT_ID === undefined) return null;
  return parseEnv(telegramEnvSchema, source);
}

const logLevelEnvSchema = z.object({
  /** The log level of this process; wins over schedule.yaml `logging.level`. Case and surrounding spaces do not matter. */
  JOB_RADAR_LOG_LEVEL: z.enum(LOG_LEVELS).optional(),
});

/** `JOB_RADAR_LOG_LEVEL`: the level, or `undefined` when unset; `invalid` when a value was set but is not a level. */
export interface LogLevelEnv {
  level: LogLevel | undefined;
  invalid: boolean;
}

/**
 * Parse `JOB_RADAR_LOG_LEVEL` on its own (not through the throwing `parseEnv`): a typo there must not take a process down
 * or override a valid schedule.yaml. Empty or blank = unset; an invalid value counts as unset and is flagged so the caller
 * can warn (naming the variable, never the value).
 */
export function parseLogLevelEnv(source: EnvSource = process.env): LogLevelEnv {
  const result = logLevelEnvSchema.safeParse(withoutEmpty({ JOB_RADAR_LOG_LEVEL: source.JOB_RADAR_LOG_LEVEL?.trim().toLowerCase() }));
  return result.success ? { level: result.data.JOB_RADAR_LOG_LEVEL, invalid: false } : { level: undefined, invalid: true };
}
