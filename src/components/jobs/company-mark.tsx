import { cn } from "@/lib/utils";

import "./jobs.css";

/**
 * Fill of a mark and the colour of its initials: token colours only, picked by a hash of the company name so a company keeps its colour.
 * The text colour goes with the fill, so every pair is >= 4.5:1 in both themes (`tests/ui/contrast.test.ts` checks them against globals.css, and that the rendered colour is the one picked):
 * `--on-signal` (ink) on the signal and highlight fills, `--on-bad` (white on paper, black on the terminal) on the green, `--ink` on the quiet greys.
 */
export const MARK_FILLS = [
  { bg: "bg-hi", text: "text-hi-ink" },
  { bg: "bg-signal-t2", text: "text-on-signal" },
  { bg: "bg-signal-t3", text: "text-on-signal" },
  { bg: "bg-signal-t4", text: "text-on-signal" },
  { bg: "bg-good", text: "text-on-bad" },
  { bg: "bg-warn", text: "text-on-signal" },
  { bg: "bg-soft", text: "text-ink" },
  { bg: "bg-grid", text: "text-ink" },
] as const;

/** Two initials of a company name ("Fernwerk AI" -> "FA", "Mosaik" -> "MO"). */
export function companyInitials(name: string): string {
  const words = name.trim().split(/[\s\-_/.&]+/).filter((word) => /[\p{L}\p{N}]/u.test(word));
  if (words.length === 0) return "?";
  const letters = words.length === 1 ? Array.from(words[0] as string).filter((c) => /[\p{L}\p{N}]/u.test(c)).slice(0, 2) : words.slice(0, 2).map((word) => Array.from(word).find((c) => /[\p{L}\p{N}]/u.test(c)) ?? "");
  return letters.join("").toUpperCase();
}

function hash(text: string): number {
  let value = 0;
  for (const char of text.toLowerCase()) value = (value * 31 + (char.codePointAt(0) ?? 0)) >>> 0;
  return value;
}

/** The company logo placeholder of a row: initials on a coloured tile (the name is written next to it, so the tile is decoration). */
export function CompanyMark({ name, className }: { name: string; className?: string }) {
  const fill = MARK_FILLS[hash(name) % MARK_FILLS.length] ?? MARK_FILLS[0];
  return (
    // the text colour is only ever set by `fill.text`: a default colour in `.jb-mark` would win over a class built at run time
    // (the `!` of a computed `${text}!` is never generated by Tailwind; ink on a dark neutral fill was 1.09:1)
    <span aria-hidden data-slot="company-mark" className={cn("jb-mark", fill.bg, fill.text, className)}>
      {companyInitials(name)}
    </span>
  );
}
